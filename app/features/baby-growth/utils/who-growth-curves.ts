/**
 * 아기의 체중/신장이 WHO 기준 몇 번째 백분위에 해당하는지 추정
 * 반환: 0-100 근사값 (P3 미만=1, P97 초과=99)
 */
export function estimatePercentile(
  value: number,
  monthAge: number,
  metric: 'weight' | 'height',
  gender: 'male' | 'female' | 'other'
): number {
  const isMale = gender !== 'female';
  const table =
    metric === 'weight'
      ? isMale ? WHO_WEIGHT_BOYS : WHO_WEIGHT_GIRLS
      : isMale ? WHO_HEIGHT_BOYS : WHO_HEIGHT_GIRLS;

  const idx = Math.min(monthAge, 24);
  const row = table[idx] ?? table[table.length - 1];

  if (value <= row.p3) return 3;
  if (value <= row.p15) return 15;
  if (value <= row.p50) return 50;
  if (value <= row.p85) return 85;
  if (value <= row.p97) return 97;
  return 99;
}
