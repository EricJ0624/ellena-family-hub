export function getAdminSignupSettingsTranslation(
  lang: LangCode,
  key: keyof AdminSignupSettingsTranslations,
): string {
  return t[lang]?.[key] ?? t.en[key] ?? t.ko[key] ?? key;
}

export function formatAdminSignupSettingsTranslation(
  lang: LangCode,
  key: keyof AdminSignupSettingsTranslations,
  vars: Record<string, string | number>,
): string {
  let text = getAdminSignupSettingsTranslation(lang, key);
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`\${${name}}`, String(value));
  }
  return text;
}
