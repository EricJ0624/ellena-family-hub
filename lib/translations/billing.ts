export function getBillingTranslation(
  lang: LangCode,
  key: keyof BillingTranslations,
): string {
  return t[lang]?.[key] ?? t.en[key] ?? t.ko[key] ?? key;
}

export function formatBillingTranslation(
  lang: LangCode,
  key: keyof BillingTranslations,
  vars: Record<string, string | number>,
): string {
  let text = getBillingTranslation(lang, key);
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`\${${name}}`, String(value));
  }
  return text;
}

const BILLING_API_CODES: Record<string, keyof BillingTranslations> = {
  promo_owner_view: 'promo_owner_view',
  promo_owner_use: 'promo_owner_use',
  not_beta: 'not_beta',
  promo_create_failed: 'promo_create_failed',
  promo_invalid: 'promo_invalid',
  promo_expired: 'promo_expired',
  promo_maxed: 'promo_maxed',
  group_missing: 'group_missing',
  plan_missing: 'plan_missing',
  BILLING_SEAT_REQUIRED: 'seat_required',
  BILLING_SUBSCRIPTION_REQUIRED: 'subscription_required',
};

export function billingApiMessage(
  lang: LangCode,
  payload: { code?: unknown; error?: unknown },
  fallback: string,
): string {
  const code = typeof payload.code === 'string' ? payload.code : '';
  const key = BILLING_API_CODES[code];
  if (key) return getBillingTranslation(lang, key);
  return typeof payload.error === 'string' && payload.error ? payload.error : fallback;
}
